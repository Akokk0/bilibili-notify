/**
 * `requirePublicAddress` —— 抓图那一层拦内网用的地址判定(ADR-0025 决策 8)。纯函数,只看一个 IP 字面量。
 *
 * 钉的是清单本身:每一段各一条拦、段的两侧各一条放行;IPv6 里嵌着 IPv4 的几种写法按里面的 v4 判。
 * 判定挂在哪一次解析上(防 DNS 重绑定)是 `HttpClient` 的事,见 `address-check.test.ts`。
 */

import { describe, expect, it } from "vite-plus/test";
import { requirePublicAddress } from "../public-address";

const refused = (address: string) =>
	expect(requirePublicAddress(address), address).toMatchObject({ ok: false, code: "invalid" });
const allowed = (address: string) =>
	expect(requirePublicAddress(address), address).toEqual({ ok: true });

describe("requirePublicAddress — IPv4", () => {
	it.each([
		["本机网络 0.0.0.0/8", "0.0.0.0", "0.255.255.255"],
		["RFC1918 10/8", "10.0.0.1", "10.255.255.255"],
		["CGNAT 100.64/10", "100.64.0.1", "100.127.255.255"],
		["回环 127/8", "127.0.0.1", "127.255.255.254"],
		["链路本地 169.254/16", "169.254.169.254", "169.254.0.1"],
		["RFC1918 172.16/12", "172.16.0.1", "172.31.255.255"],
		["IETF 协议保留 192.0.0/24", "192.0.0.1", "192.0.0.255"],
		["文档段 192.0.2/24", "192.0.2.1", "192.0.2.255"],
		["RFC1918 192.168/16", "192.168.0.1", "192.168.255.255"],
		["基准测试 198.18/15", "198.18.0.1", "198.19.255.255"],
		["文档段 198.51.100/24", "198.51.100.1", "198.51.100.255"],
		["文档段 203.0.113/24", "203.0.113.1", "203.0.113.255"],
		["组播 224/4", "224.0.0.1", "239.255.255.255"],
		["保留 240/4 与广播", "240.0.0.1", "255.255.255.255"],
	])("拦 %s", (_name, low, high) => {
		refused(low);
		refused(high);
	});

	it.each([
		"1.1.1.1",
		"9.255.255.255",
		"11.0.0.0",
		"100.63.255.255",
		"100.128.0.0",
		"126.255.255.255",
		"128.0.0.1",
		"169.253.255.255",
		"169.255.0.0",
		"172.15.255.255",
		"172.32.0.0",
		"192.0.1.1",
		"192.0.3.1",
		"192.167.255.255",
		"192.169.0.0",
		"198.17.255.255",
		"198.20.0.0",
		"198.51.99.255",
		"198.51.101.0",
		"203.0.112.255",
		"203.0.114.0",
		"223.255.255.255",
	])("放行公网 %s(段的边界外)", (address) => {
		allowed(address);
	});
});

describe("requirePublicAddress — IPv6", () => {
	it.each([
		["未指定 ::", "::"],
		["回环 ::1", "::1"],
		["回环的全写", "0:0:0:0:0:0:0:1"],
		["v4 兼容(已废弃)::/96", "::10.0.0.1"],
		["本地用 NAT64 64:ff9b:1::/48", "64:ff9b:1::1"],
		["Teredo 2001::/32", "2001:0:4136:e378:8000:63bf:3fff:fdd2"],
		["文档段 2001:db8::/32", "2001:db8::1"],
		["ULA fc00::/7", "fc00::1"],
		["ULA fd 开头", "fd12:3456:789a::1"],
		["链路本地 fe80::/10", "fe80::1"],
		["链路本地带区号", "fe80::1%en0"],
		["站点本地(已废弃)fec0::/10", "fec0::1"],
		["组播 ff00::/8", "ff02::1"],
	])("拦 %s", (_name, address) => {
		refused(address);
	});

	it.each([
		["v4 映射,点分写法", "::ffff:127.0.0.1", "::ffff:1.1.1.1"],
		["v4 映射,十六进制写法", "::ffff:a00:1", "::ffff:101:101"],
		["NAT64 64:ff9b::/96", "64:ff9b::10.0.0.1", "64:ff9b::1.1.1.1"],
		["NAT64 十六进制写法", "64:ff9b::c0a8:1", "64:ff9b::808:808"],
		["6to4 2002::/16", "2002:a00:1::1", "2002:101:101::1"],
		["6to4 嵌着回环", "2002:7f00:1::", "2002:808:808::"],
	])("%s:按里面的 v4 判", (_name, internal, external) => {
		refused(internal);
		allowed(external);
	});

	it.each(["2400:3200::1", "2606:4700:4700::1111", "2001:4860:4860::8888", "fbff::1", "fe7f::1"])(
		"放行公网 %s",
		(address) => {
			allowed(address);
		},
	);

	it("大小写与方括号都认", () => {
		refused("FE80::1");
		refused("[::1]");
		allowed("[2606:4700:4700::1111]");
	});
});

describe("requirePublicAddress — 不是 IP", () => {
	it.each([
		"",
		"localhost",
		"example.com",
		"1.2.3",
		"1.2.3.4.5",
		"256.1.1.1",
		"12345::1",
		"::1::2",
	])("%j 不是 IP 字面量 → invalid(主机名要先解析,判的是解析出来的地址)", (address) => {
		refused(address);
	});
});
