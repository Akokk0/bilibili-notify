import { randomBytes } from "node:crypto";
import { readFile } from "node:fs/promises";
import type { Logger } from "@bilibili-notify/internal";
import { atomicWriteFile } from "./atomic-file";
import { KeyManager, parseMasterKeyHex } from "./key-manager";
import { deriveKeyFromPassphrase } from "./secret-box";

/**
 * Resolves the 32-byte AES key used to encrypt at-rest secrets.
 *
 * Two strategies:
 *   - {@link PassphraseKeyProvider} — key scrypt-derived from an injected
 *     passphrase (`bootstrap.cookieEncryptionKey` / `BN_COOKIE_KEY`). The key
 *     itself is NEVER written to disk; only a non-secret per-install salt is.
 *     This is the only mode that gives real at-rest protection.
 *   - {@link FileKeyProvider} — legacy behaviour: a random key file living
 *     next to the ciphertext (auto-generated by {@link KeyManager}). Key and
 *     data co-located → obfuscation, not protection. Kept as the zero-config
 *     fallback.
 *
 * Deliberately no in-place rotation: the same key also encrypts the server's
 * config secrets, whose store caches it per process. Rotating it under a live
 * process left that store writing with the old key → next boot can't decrypt
 * → every AI / search key silently dropped (0.12.0).
 */
export interface KeyProvider {
	getKey(): Promise<Buffer>;
	/** `true` = injected passphrase (real encryption); `false` = co-located key file. */
	readonly protected: boolean;
}

export class FileKeyProvider implements KeyProvider {
	readonly protected = false;
	private readonly km: KeyManager;
	private keyPromise: Promise<Buffer> | null = null;
	constructor(keyPath: string, logger: Logger) {
		this.km = new KeyManager(keyPath, logger);
	}
	getKey(): Promise<Buffer> {
		if (this.keyPromise) return this.keyPromise;
		const p = this.km.loadOrCreate();
		this.keyPromise = p;
		p.catch(() => {
			if (this.keyPromise === p) this.keyPromise = null;
		});
		return p;
	}
}

export class PassphraseKeyProvider implements KeyProvider {
	readonly protected = true;
	private cached: Buffer | null = null;
	constructor(
		private readonly passphrase: string,
		private readonly saltPath: string,
		private readonly logger: Logger,
	) {}

	async getKey(): Promise<Buffer> {
		if (this.cached) return this.cached;
		const salt = await this.loadOrCreateSalt();
		this.cached = deriveKeyFromPassphrase(this.passphrase, salt);
		this.logger.debug("[key] 使用注入密钥派生 AES-256 密钥 (scrypt)");
		return this.cached;
	}

	private async loadOrCreateSalt(): Promise<Buffer> {
		let hex: string | null = null;
		try {
			hex = (await readFile(this.saltPath, "utf8")).trim();
		} catch (e) {
			if ((e as NodeJS.ErrnoException).code !== "ENOENT") {
				// 文件存在但读不了(EACCES/EIO…):绝不能静默重生成 —— 那会换 key,
				// 把所有用注入密钥加密的 secrets 一次性变为无法解密且无声重登。
				this.logger.error(`[key] kdf.salt 读取失败（非缺失）: ${(e as Error).message}`);
				throw e;
			}
			// ENOENT → 首次运行,正常创建
		}
		if (hex !== null) {
			const salt = parseSaltHex(hex);
			if (salt) return salt;
			this.logger.warn(
				"[key] kdf.salt 格式非法（非 32 位十六进制），将重新生成 —— " +
					"既有用注入密钥加密的 secrets（来源凭据 / AI apiKey）届时无法解密、需重新登录。",
			);
		}
		const salt = randomBytes(16);
		// P2:原子写用唯一 tmp(pid + rand)。固定 `${saltPath}.tmp` 在并发首启
		// (两进程同时无 salt)时互相覆盖 tmp → rename 出错乱 salt。
		// salt 不是秘密,但与 master.key 同住 secrets 目录,权限一并收成 0o600。
		await atomicWriteFile(this.saltPath, salt.toString("hex"), { mode: 0o600 });
		return salt;
	}
}

export interface CreateKeyProviderOptions {
	/** Injected passphrase. When present → PassphraseKeyProvider; else FileKeyProvider. */
	passphrase?: string;
	/** Legacy random-key file path (FileKeyProvider). */
	keyPath: string;
	/** Per-install scrypt salt path (PassphraseKeyProvider). */
	saltPath: string;
	logger: Logger;
}

export function createKeyProvider(opts: CreateKeyProviderOptions): KeyProvider {
	const pass = opts.passphrase?.trim();
	if (pass) return new PassphraseKeyProvider(pass, opts.saltPath, opts.logger);
	// 回退选择点统一打高可见告警 —— 此前仅 standalone 的 bootstrap.ts 警示,
	// 任何其它调用方落到回退时静默无声。
	// 文案保持端中立(不提 BN_COOKIE_KEY,那是 standalone 专属);standalone
	// 在 bootstrap 另加可执行指引。
	opts.logger.warn(
		"[key] 未提供注入密钥:secrets（来源凭据 / AI apiKey）使用本地随机密钥，" +
			"且密钥与密文同目录 —— 仅为混淆，不构成真正的静态加密。",
	);
	return new FileKeyProvider(opts.keyPath, opts.logger);
}

/**
 * 口令派生用的盐:精确 32 位十六进制 = 16 字节(本模块只写 randomBytes(16))。放宽到
 * {32,} 会接受被截断 / 拼接的 salt,静默派生出错 key → 无声重登。
 */
function parseSaltHex(text: string): Buffer | null {
	const hex = text.trim();
	return /^[0-9a-f]{32}$/i.test(hex) ? Buffer.from(hex, "hex") : null;
}

export type KeyMaterialRead = { kind: "ok"; key: Buffer } | { kind: "missing" };

/**
 * 只读地取这一处的密钥:和 {@link createKeyProvider} 选同一种(有口令就派生,否则读 master.key),
 * 拿到的是同一把;缺了、或者文件内容不认,回 `missing`,**绝不写盘**。
 *
 * 给迁移开新代用(ADR-0022):会话签名要的密钥得从迁移来源取,而来源(第 0 代)一个字节都不许动,
 * `getKey()` 缺文件就当场造一把写进去,不能拿来读来源。缺了的,由新代里的 provider 自己去建。
 */
export async function readKeyMaterial(
	opts: Omit<CreateKeyProviderOptions, "logger">,
): Promise<KeyMaterialRead> {
	const pass = opts.passphrase?.trim();
	const text = await readTextIfExists(pass ? opts.saltPath : opts.keyPath);
	if (text === null) return { kind: "missing" };
	if (pass) {
		const salt = parseSaltHex(text);
		return salt ? { kind: "ok", key: deriveKeyFromPassphrase(pass, salt) } : { kind: "missing" };
	}
	const key = parseMasterKeyHex(text);
	return key ? { kind: "ok", key } : { kind: "missing" };
}

/** 读得到就回内容,文件不在回 null;别的读错(EACCES / EIO…)照抛,和 provider 一样不当缺失。 */
async function readTextIfExists(path: string): Promise<string | null> {
	try {
		return await readFile(path, "utf8");
	} catch (e) {
		if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
		throw e;
	}
}
