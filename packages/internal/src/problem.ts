/**
 * 问题表里的一条。全在内存,重启清空。
 *
 * 「问题」说的是一件主人该知道、而又不是某一条推送出了岔子的事:登录失效了、某个房间不监听了、
 * 某个连接连不上了。报的人把它报给核心,核心统一记日志、给面板看、必要时私聊主人;
 * 报的人自己负责说它什么时候好了。
 */
export interface Problem {
	/** 报的人:集成键(来源键、适配器键、拓展 id),或 `"core"`。 */
	reporter: string;
	/** 关于谁;不带就是报的人自己的问题。目前只有订阅这一支。 */
	about?: { subscriptionId: string };
	/** snake 风格;不受标准失败码表约束。同一个报的人、同一个对象下,同一个 code 只有一条。 */
	code: string;
	message: string;
	/** 第一次出现的时刻(ISO)。重复报不重置。 */
	since: string;
}
